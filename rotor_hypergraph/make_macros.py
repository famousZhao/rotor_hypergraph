"""Emit manuscript/macros.tex.

Every quantitative value quoted in the running text of the manuscript is a
macro defined here, so that no number is typed by hand into the prose.  If a
result file is missing the macro expands to a visible placeholder.
"""
import json
import numpy as np

from config import (FS, N_POINTS, RESULTS, PROJ, CLASSES)

OUT = PROJ / "manuscript" / "macros.tex"
METHODS = ["lpf_sem", "raw_se", "mi", "acf", "cc"]
PLACE = r"\textsc{tbd}"


def _load(name):
    p = RESULTS / name
    if not p.exists():
        print("  missing", name)
        return None
    return json.loads(p.read_text())


def _pct(v, d=2):
    return f"{100 * v:.{d}f}\\%"


def _num(v, d=3):
    return f"{v:.{d}f}"


class Macros:
    def __init__(self):
        self.d = {}

    def set(self, name, value):
        self.d[name] = value

    def tex(self, name, value):
        self.d[name] = str(value)

    def render(self):
        lines = ["% generated by src/make_macros.py, do not edit",
                 ""]
        for k in sorted(self.d):
            lines.append(f"\\newcommand{{\\{k}}}{{{self.d[k]}}}")
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text("\n".join(lines) + "\n")
        print("  wrote", OUT.name, f"({len(self.d)} macros)")


def main():
    m = Macros()
    # ---- setup, always available
    m.tex("nSignals", "180")
    m.tex("nPerClass", "45")
    m.tex("nPts", f"{N_POINTS}")
    m.tex("nClassNames", "the four measured states")
    m.tex("nMfptSignals", "135")
    m.tex("nMfptPerClass", "45")
    m.tex("nMfptClasses", "three bearing states")
    m.tex("nMfptPts", "2048")

    # ---- experiment 1
    d1 = _load("exp1.json")
    if d1:
        ca = d1["chaos_accuracy"]
        systems = list(ca.keys())
        for meth, tag in [("lpf_sem", "LPF"), ("raw_se", "SE"),
                          ("mi", "MI"), ("cc", "CC"), ("acf", "ACF")]:
            vals = [ca[s]["methods"][meth]["tau_err"] for s in systems]
            m.tex(f"chaosTau{tag}", _pct(np.mean(vals)))
        vals = [ca[s]["methods"]["lpf_sem"]["lle_err"] for s in systems]
        m.tex("lleErrLPF", _pct(np.mean(vals), 1))
        m.tex("lleErrSE", _pct(np.mean([ca[s]["methods"]["raw_se"]["lle_err"]
                                       for s in systems]), 1))
        # How often each rule attains the smallest delay error on the benchmark.
        win = {"lpf_sem": 0, "raw_se": 0, "mi": 0, "acf": 0, "cc": 0}
        for s in systems:
            errs = {mm: ca[s]["methods"][mm]["tau_err"] for mm in win}
            best = min(errs, key=errs.get)
            win[best] += 1
        for meth, tag in [("lpf_sem", "LPF"), ("raw_se", "SE"),
                          ("mi", "MI"), ("acf", "ACF"), ("cc", "CC")]:
            m.tex(f"chaosWin{tag}", f"{win[meth]}")
        m.tex("nSystems", f"{len(systems)}")

        cn = d1["chaos_noise"]
        snrs = sorted({float(k) for v in cn.values() for k in v["snr"]})
        lo = str(int(snrs[0]))          # most severe noise, -5 dB
        mid = str(int(snrs[1]))         # next point up, 0 dB
        m.tex("snrLow", lo)
        m.tex("snrMid", mid)
        # Headline noise numbers are quoted in the moderate regime, where both
        # rules still produce a delay; the severe point is reported separately
        # because the filtered derivative collapses there.
        for meth, tag in [("lpf_sem", "LPF"), ("raw_se", "SE"),
                          ("mi", "MI"), ("cc", "CC")]:
            vals = [cn[s]["snr"][mid][meth]["rel_err"] for s in cn]
            m.tex(f"noiseRel{tag}", _pct(np.mean(vals), 1))
            vals = [cn[s]["snr"][lo][meth]["rel_err"] for s in cn]
            m.tex(f"noiseRelLow{tag}", _pct(np.mean(vals), 1))

        rn = d1["rotor_noise"]
        for meth, tag in [("lpf_sem", "LPF"), ("raw_se", "SE"),
                          ("mi", "MI"), ("cc", "CC")]:
            m.tex(f"rotorNoise{tag}",
                  _num(rn["snr"][mid][meth]["mean_abs_dev"], 1))
            m.tex(f"rotorNoiseLow{tag}",
                  _num(rn["snr"][lo][meth]["mean_abs_dev"], 1))

        # Stability of the delay across records of the measured set is the
        # property the saturated rule actually changes most clearly.
        rt = d1["rotor_tau"]["per_class"]
        for meth, tag in [("lpf_sem", "LPF"), ("raw_se", "SE"),
                          ("mi", "MI"), ("acf", "ACF"), ("cc", "CC")]:
            stds = [rt[c][meth]["tau_std"] for c in rt]
            m.tex(f"rotorTauStd{tag}", _num(np.mean(stds), 2))

    # ---- experiment 2
    d2 = _load("exp2.json")
    if d2:
        f = d2["filter"]
        allt = []
        for key in ("orders", "cutoffs", "alphas"):
            allt += [f[key][k]["tau_mean"] for k in f[key]]
        m.tex("sensTauSpan", f"{max(allt) - min(allt):.0f}")
        rr = d2["community"]["remove_ratio"]
        accs = [rr[k]["nc_cv_acc"] for k in rr]
        m.tex("sensCvSpan", _num(max(accs) - min(accs), 2))

    # ---- experiment 3
    dm = _load("exp3_methods.json")
    if dm:
        for meth, tag in [("lpf_sem", "LPF"), ("raw_se", "SE"),
                          ("cc", "CC"), ("mi", "MI"), ("acf", "ACF")]:
            if meth in dm["methods"]:
                v = dm["methods"][meth]["separability"]["nc_cv_acc"]
                m.tex(f"mechCvAcc{tag}", _num(v, 2))
        hedges = [dm["methods"][mm]["hedge_mean"] for mm in dm["methods"]]
        m.tex("mechHedgeMin", _num(min(hedges), 1))
        m.tex("mechHedgeMax", _num(max(hedges), 1))

    # ---- experiment 3, per-state descriptor (Misalignment spectral spread)
    d3f = _load("exp3_full.json")
    if d3f and "per_class" in d3f:
        v = d3f["per_class"]["3"]["algebraic_connectivity"]
        m.tex("algebraicMis", f"{v['mean']:.2f} $\\pm$ {v['std']:.2f}")

    # ---- experiment 14: fixed-global-tau separability sweep (de-collinearise)
    d14 = _load("exp14_fixedtau.json")
    if d14 and "fixed_tau" in d14:
        ft = d14["fixed_tau"]
        m.tex("sepFixTwo", _num(ft["2"]["nc_cv_acc"], 3))
        m.tex("sepFixTen", _num(ft["10"]["nc_cv_acc"], 3))
        ad = d14["adaptive_tauc"]
        m.tex("sepAdaptive", _num(ad["nc_cv_acc"], 3))
        m.tex("sepAdaptiveGain", _num(ad["nc_cv_acc"] - ft["2"]["nc_cv_acc"], 3))
        m.tex("sepPeakTau", "2")

    # ---- experiment 4
    d4 = _load("exp4_multires.json")
    if d4:
        m.tex("mrCombined", _num(d4["combined"]["separability"]["nc_cv_acc"], 2))
        lv = d4["levels"]
        best = max(lv[k]["separability"]["nc_cv_acc"] for k in lv)
        m.tex("mrBestLevel", _num(best, 2))

    # ---- experiment 5
    d5 = _load("exp5.json")
    if d5:
        v = d5["variants"]
        for k, tag in [("full", "Full"), ("ablation_A_psr_cc", "A"),
                       ("ablation_B_louvain", "B")]:
            if k in v:
                m.tex(f"abl{tag}", _num(v[k]["separability"]["nc_cv_acc"], 2))

    # ---- experiment 6
    d6 = _load("exp6.json")
    if d6:
        st = d6["stages_mean_over_5"]
        m.tex("pipeTime", _num(st["full_pipeline"], 1))
        dom = max(("recurrence_network", "ni_louvain", "hypergraph_features"),
                  key=lambda k: st.get(k, 0.0))
        m.tex("domStage",
              {"recurrence_network": "recurrence construction",
               "ni_louvain": "community detection",
               "hypergraph_features": "feature extraction"}[dom])
        # The saturated estimator is a filter and a derivative on top of an
        # entropy curve that is computed anyway; the C-C baseline pays for a
        # correlation integral.
        m.tex("lpfCost", _num(st.get("symbolic_entropy_curve", 0.0)
                              + st.get("lpf_smooth_and_derivative", 0.0), 2))
        m.tex("ccCost", _num(st.get("cc_method", 0.0), 1))
        m.tex("domCost", _num(st.get(dom, 0.0), 1))
        # the optimised overlapping-community stage against the one it
        # replaces, both timed on the same signal and machine
        if "ni_louvain_reference" in st and st["ni_louvain"] > 0:
            m.tex("niRef", _num(st["ni_louvain_reference"], 2))
            m.tex("niFast", _num(st["ni_louvain"], 2))
            m.tex("niSpeedup",
                  f"{st['ni_louvain_reference'] / st['ni_louvain']:.0f}")

    # ---- experiment 7, classification against mainstream pipelines
    c7r = _load("exp7_rotor.json")
    c7m = _load("exp7_mfpt.json")

    def _cls(d, cond="normalised"):
        """(best accuracy, name of the best pipeline) for one dataset."""
        if not d or cond not in d["conditions"]:
            return None, None
        blk = d["conditions"][cond]["pipelines"]
        best = max(blk, key=lambda k: blk[k]["best_acc"])
        return blk[best]["best_acc"], best

    def _cls_named(d, name, cond="normalised"):
        if not d or cond not in d["conditions"]:
            return None
        blk = d["conditions"][cond]["pipelines"]
        return blk[name]["best_acc"] if name in blk else None

    HG = "hypergraph, saturated delay"
    HGSE = "hypergraph, entropy delay"
    HGMI = "hypergraph, MI delay"
    HGMR = "hypergraph, multi-resolution"
    MAIN = "VMD mode entropies"

    if c7r:
        v = _cls_named(c7r, HG)
        m.tex("clsRotorHg", _num(v, 2) if v is not None else PLACE)
        v = _cls_named(c7r, HGMR)
        m.tex("clsRotorHgMr", _num(v, 2) if v is not None else PLACE)
        b, bn = _cls(c7r)
        m.tex("clsRotorBest", _num(b, 2) if b is not None else PLACE)
        m.tex("clsRotorBestName", bn if bn else PLACE)
        v2 = _cls_named(c7r, HGSE)
        m.tex("clsRotorHgSE", _num(v2, 2) if v2 is not None else PLACE)
        v2b = _cls_named(c7r, HGMI)
        m.tex("clsRotorHgMI", _num(v2b, 2) if v2b is not None else PLACE)
        v3 = _cls_named(c7r, MAIN)
        m.tex("clsRotorVmd", _num(v3, 2) if v3 is not None else PLACE)
        r = c7r["conditions"].get("as-recorded", {}).get("pipelines", {})
        m.tex("clsRotorHgRaw", _num(r[HG]["best_acc"], 2) if HG in r else PLACE)
    if c7m:
        v = _cls_named(c7m, HG)
        m.tex("clsMfptHg", _num(v, 2) if v is not None else PLACE)
        v = _cls_named(c7m, HGMR)
        m.tex("clsMfptHgMr", _num(v, 2) if v is not None else PLACE)
        v2b = _cls_named(c7m, HGMI)
        m.tex("clsMfptHgMI", _num(v2b, 2) if v2b is not None else PLACE)
        b, bn = _cls(c7m)
        m.tex("clsMfptBest", _num(b, 2) if b is not None else PLACE)
        m.tex("clsMfptBestName", bn if bn else PLACE)
        v3 = _cls_named(c7m, MAIN)
        m.tex("clsMfptVmd", _num(v3, 2) if v3 is not None else PLACE)
        r = c7m["conditions"].get("as-recorded", {}).get("pipelines", {})
        m.tex("clsMfptRawTd", _num(r["time-domain statistics"]["best_acc"], 2)
              if "time-domain statistics" in r else PLACE)
        m.tex("clsMfptRawVmd", _num(r[MAIN]["best_acc"], 2)
              if MAIN in r else PLACE)
        m.tex("clsMfptHgRaw", _num(r[HG]["best_acc"], 2) if HG in r else PLACE)

    # ---- experiment 8, propagation of delay stability
    p8 = _load("exp8_rotor.json")
    if p8:
        for meth, tag in [("lpf_sem", "LPF"), ("raw_se", "SE"),
                          ("mi", "MI")]:
            if meth not in p8["methods"]:
                continue
            r = p8["methods"][meth]
            for k, kt in [("clean", "Clean"), ("15", "Fifteen"),
                          ("10", "Ten"), ("5", "Five")]:
                if k in r:
                    m.tex(f"propAcc{kt}{tag}", _num(r[k]["nc_cv_acc"], 3))
                    m.tex(f"propDisp{kt}{tag}", _num(r[k]["tau_dispersion"], 2))
        mr = p8.get("multiresolution", {}).get("methods", {})
        for meth, tag in [("lpf_sem", "LPF"), ("raw_se", "SE")]:
            if meth not in mr:
                continue
            for k, kt in [("clean", "Clean"), ("10", "Ten")]:
                if k in mr[meth]:
                    m.tex(f"propMr{kt}{tag}", _num(mr[meth][k]["combined"], 3))
        dd = p8.get("delay_dispersion", {}).get("conditions", {})
        for k, kt in [("clean", "Clean"), ("10", "Ten"), ("5", "Five"),
                      ("0", "Zero")]:
            if k not in dd:
                continue
            for meth, tag in [("lpf_sem", "LPF"), ("raw_se", "SE"),
                              ("mi", "MI")]:
                if meth in dd[k]:
                    m.tex(f"disp{kt}{tag}",
                          _num(dd[k][meth]["tau_dispersion"], 2))

    # ---- experiment 9, estimator variants (Path-1 / Path-2 review)
    d9 = _load("exp9_variants.json")
    if d9:
        ca9, cn9 = d9["chaos_accuracy"], d9["chaos_noise"]
        rt9 = d9["rotor_tau"]["per_method"]
        rn9 = d9["rotor_noise"]
        systems9 = list(ca9.keys())
        tag9 = {"lpf_sem": "LPF", "raw_se": "SE",
                "lpf_curv": "CURV", "lpf_fit": "FIT", "lpf_adaptive": "ADP",
                "pe_sem": "PE", "mi": "MI", "acf": "ACF", "cc": "CC"}
        for meth, tg in tag9.items():
            vals = [ca9[s]["methods"][meth]["tau_err"] for s in systems9]
            m.tex(f"varTau{tg}", _pct(np.mean(vals)))
            nv = [cn9[s]["snr"]["10"][meth]["rel_err"] for s in cn9]
            m.tex(f"varNoise{tg}", _pct(np.mean(nv), 1))
            m.tex(f"varRotorStd{tg}", _num(rt9[meth]["tau_std"], 2))
            m.tex(f"varRatio{tg}", _num(rt9[meth]["stability_ratio"], 1))
            m.tex(f"varRotorNoise{tg}",
                  _num(rn9["snr"]["10"][meth]["mean_abs_dev"], 1))

    # ---- experiment 10 / 11 / 12, delay scale against the descriptor
    # exp11: full-180 clean separability; exp12: same after per-record
    # amplitude normalisation; exp10: n-per-class=12, 3-seed protocol giving
    # the noise column and the delay dispersion under 10 dB.
    d11 = _load("exp11_fullsep.json")
    d12 = _load("exp12_normsep.json")
    d10 = _load("exp10_downstream.json")
    tag11 = {"lpf_sem": "LPF", "raw_se": "SE", "lpf_fit": "FIT",
             "lpf_curv": "CURV", "lpf_adaptive": "ADP", "pe_sem": "PE",
             "mi": "MI"}
    for meth, tg in tag11.items():
        if d11 and meth in d11["methods"]:
            v = d11["methods"][meth]
            m.tex(f"sepClean{tg}", _num(v["nc_cv_acc"], 3))
            m.tex(f"tauScale{tg}", _num(v["tau_mean"], 1))
        if d12 and meth in d12["methods"]:
            m.tex(f"sepNorm{tg}", _num(d12["methods"][meth]["nc_cv_acc"], 3))
        if d10 and meth in d10["methods"]:
            if "10" in d10["methods"][meth]:
                r = d10["methods"][meth]["10"]
                m.tex(f"sepTen{tg}", _num(r["nc_cv_acc"], 3))
                m.tex(f"sepDispTen{tg}", _num(r["tau_dispersion"], 2))
            if "clean" in d10["methods"][meth]:
                r = d10["methods"][meth]["clean"]
                m.tex(f"sepDispClean{tg}", _num(r["tau_dispersion"], 2))

    # ---- experiment 13, extreme-noise robustness of the delay rules
    # delay_dev: rotor delay deviation (samples) at 0 dB and -5 dB; downstream:
    # separability and delay dispersion at n-per-class=12, three seeds.
    d13 = _load("exp13_extreme.json")
    if d13:
        dd13 = d13["delay_dev"]["snr"]
        dn13 = d13["downstream"]["methods"]
        tag13 = {"lpf_sem": "LPF", "raw_se": "SE", "lpf_fit": "FIT",
                 "lpf_curv": "CURV", "lpf_adaptive": "ADP", "pe_sem": "PE",
                 "mi": "MI"}
        for meth, tg in tag13.items():
            if meth in dd13.get("0", {}):
                m.tex(f"devZero{tg}", _num(dd13["0"][meth]["mean_abs_dev"], 2))
            if meth in dd13.get("-5", {}):
                m.tex(f"devLow{tg}", _num(dd13["-5"][meth]["mean_abs_dev"], 1))
            if meth in dn13:
                for k, kt in [("0", "Zero"), ("-5", "Low")]:
                    if k in dn13[meth]:
                        m.tex(f"sep{kt}{tg}", _num(dn13[meth][k]["nc_cv_acc"], 3))
                        m.tex(f"disp{kt}{tg}", _num(dn13[meth][k]["tau_dispersion"], 2))

    # placeholders for anything a missing result left undefined
    for name in ["chaosTauLPF", "chaosTauSE", "chaosTauMI", "chaosTauCC",
                 "chaosTauACF", "lleErrLPF", "lleErrSE", "snrLow", "snrMid",
                 "nSystems", "chaosWinLPF", "chaosWinSE", "chaosWinMI",
                 "chaosWinACF", "chaosWinCC",
                 "noiseRelLPF", "noiseRelSE", "noiseRelMI", "noiseRelCC",
                 "noiseRelLowLPF", "noiseRelLowSE", "noiseRelLowMI",
                 "noiseRelLowCC",
                 "rotorNoiseLPF", "rotorNoiseSE", "rotorNoiseMI",
                 "rotorNoiseCC", "rotorNoiseLowLPF", "rotorNoiseLowSE",
                 "rotorNoiseLowMI", "rotorNoiseLowCC",
                 "rotorTauStdLPF", "rotorTauStdSE", "rotorTauStdMI",
                 "rotorTauStdACF", "rotorTauStdCC",
                 "sensTauSpan", "sensCvSpan", "mechCvAccLPF", "mechCvAccSE",
                 "mechCvAccCC", "mechCvAccMI", "mechCvAccACF",
                 "mechHedgeMin", "mechHedgeMax", "mrCombined",
                 "mrBestLevel", "ablFull", "ablA", "ablB", "pipeTime",
                 "domStage", "lpfCost", "ccCost", "domCost",
                 "clsRotorHg", "clsRotorHgMr", "clsRotorBest", "clsRotorBestName",
                 "clsRotorHgSE", "clsRotorHgMI", "clsRotorVmd", "clsRotorHgRaw",
                 "clsMfptHg", "clsMfptHgMr", "clsMfptHgMI", "clsMfptBest", "clsMfptBestName",
                 "clsMfptVmd", "clsMfptRawTd", "clsMfptRawVmd", "clsMfptHgRaw",
                 "propAccCleanLPF", "propAccCleanSE", "propAccCleanMI",
                 "propAccFifteenLPF", "propAccFifteenSE", "propAccFifteenMI",
                 "propAccTenLPF", "propAccTenSE", "propAccTenMI",
                 "propAccFiveLPF", "propAccFiveSE", "propAccFiveMI",
                 "propDispCleanLPF", "propDispCleanSE", "propDispCleanMI",
                 "propDispFifteenLPF", "propDispFifteenSE", "propDispFifteenMI",
                 "propDispTenLPF", "propDispTenSE", "propDispTenMI",
                 "propDispFiveLPF", "propDispFiveSE", "propDispFiveMI",
                 "propMrCleanLPF", "propMrCleanSE", "propMrTenLPF",
                 "propMrTenSE", "dispCleanLPF", "dispCleanSE", "dispTenLPF",
                 "dispTenSE", "dispFiveLPF", "dispFiveSE", "dispZeroLPF",
                 "dispZeroSE", "dispCleanMI", "dispTenMI", "dispFiveMI",
                 "dispZeroMI", "nMfptSignals", "nMfptPerClass",
                 "nMfptClasses", "nMfptPts", "niSpeedup", "niRef",
                 "niFast"]:
        m.d.setdefault(name, PLACE)
    for tg in ["LPF", "SE", "CURV", "FIT", "ADP", "PE", "MI", "ACF",
               "CC"]:
        for base in ["varTau", "varNoise", "varRotorStd", "varRatio",
                     "varRotorNoise"]:
            m.d.setdefault(f"{base}{tg}", PLACE)
    for tg in ["LPF", "SE", "FIT", "CURV", "ADP", "PE", "MI"]:
        for base in ["sepClean", "sepNorm", "tauScale"]:
            m.d.setdefault(f"{base}{tg}", PLACE)
        for base in ["sepClean", "sepTen", "sepDispClean", "sepDispTen"]:
            m.d.setdefault(f"{base}{tg}", PLACE)
        for base in ["devZero", "devLow", "sepZero", "sepLow", "dispZero", "dispLow"]:
            m.d.setdefault(f"{base}{tg}", PLACE)

    m.render()


if __name__ == "__main__":
    main()
